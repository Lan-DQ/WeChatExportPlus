# -*- coding: utf-8 -*-
"""AI 提示词：随每份导出一起交给 AI 的「使用须知 + 角色指令」。

设计
----
提示词有两份：

1. 内置默认（DEFAULT_PROMPT）—— 保证程序在缺少外部文件时也能正常工作；
2. 外部可编辑文件 `AI提示词.txt`（放在 exe 同目录）—— 用户可以直接改，
   改完立即生效，**不需要重新打包程序**。

读取优先级：exe 同目录的 `AI提示词.txt` → 内置默认。
文件内容为空或读不到时，一律回退到内置默认，绝不让导出缺少这段说明。

为什么必须写进每个导出文件里
----------------------------
用户是把单个 `.md` 拖进 DeepSeek 网页版。网页版没有"系统提示词"这个概念，
所以这段要求必须**内嵌在文件正文里**，AI 才会读到。
"""
import os

MARKER = '给 AI 的指令'

DEFAULT_PROMPT = """【角色】
你是我的私人助理兼顾问。本次对话的所有材料是我本人的微信聊天记录导出文件，
你可以直接引用、检索、总结其中的内容。

【最重要的一条约束：你不知道图片里有什么】
本文件只有文字。聊天记录里形如 [图片0001]、[图片0002] 的标记，
代表「这里原本有一张图片」，但图片内容你完全看不到。图片文件放在与本文件同名的
「_图片」文件夹里，按 0001.jpg、0002.jpg 编号，与正文编号严格对应。

因此：
- 绝对不要猜测、编造或"合理推断"图片内容，也不要把 [图片NNNN] 当成已知信息使用；
- 当某张图片对回答我的问题很关键时，直接告诉我编号，
  我会把图上传给你，你再继续分析；
- 如果某个结论只靠文字不充分、需要看图才能确认，请明确说明这一点。

【其他拿不到内容的消息类型】
- [语音 N秒] / [视频 N秒]：只有时长，没有内容，也没有转写。
- [链接] / [小程序] / [公众号]：只有标题和链接，正文没有导出，你无法访问这些链接。
- [文件] 文件名(大小)：只有文件名，文件本体没有导出。
- [表情]：只有占位符，看不到表情图。
- [聊天记录]：转发内容已展开为文本，可正常阅读。
- (系统) 开头的消息是系统提示（谁入群、谁撤回等），不是某人说的话。

遇到上面这些类型时，先说清"这里是什么类型的消息、内容看不到"，
并指出位置（时间 + 发言人），让我能自己回去查，不要跳过不提。

【分析纪律】
- 只依据文件里实际存在的文字作答；查不到就说查不到，不要用常识补齐。
- 时间顺序很重要：同一件事可能前后说法变了，注意按 [时间] 排序核对，
  如果有信息变更或前后矛盾，明确指出"哪一天说的、后来哪一天改口了"。
- 涉及金额、时间、地点、人名等关键信息时，尽量给出出处（时间 + 发言人），
  便于我核对。

【回答风格】
- 先给简短结论（几句话说清），需要时再展开细节。
- 不确定的地方标注"不确定"，并说明缺什么信息才能确定。
- 我要的是能直接用的答案，不要复述我已知的背景。

【优先级】
以上是默认工作方式。如果我当次的指令与上面冲突，一律以我的指令为准。"""

_CACHE = {}


def prompt_path(base_dir):
    """外部提示词文件路径。"""
    return os.path.join(base_dir or '', 'AI提示词.txt')


def load_prompt(base_dir):
    """读取提示词。外部文件优先；为空/缺失则用内置默认。"""
    key = os.path.abspath(base_dir or '')
    if key in _CACHE:
        return _CACHE[key]
    text = ''
    p = prompt_path(base_dir)
    try:
        if base_dir and os.path.exists(p):
            with open(p, encoding='utf-8', errors='replace') as f:
                text = f.read().strip()
    except OSError:
        text = ''
    result = text or DEFAULT_PROMPT
    _CACHE[key] = result
    return result


def clear_cache():
    """用户改完提示词后调用，强制下次重新读取。"""
    _CACHE.clear()


def as_markdown(prompt):
    """把提示词转成 Markdown 段落，插在会话正文之前。"""
    body = (prompt or '').strip()
    if not body:
        return ''
    lines = ['## ' + MARKER, '']
    # 用引用块包起来，视觉上和下面真正的聊天正文区分开，AI 也读得懂
    for line in body.split('\n'):
        lines.append(('> ' + line).rstrip() if line.strip() else '>')
    lines.append('')
    lines.append('---')
    lines.append('')
    return '\n'.join(lines)
